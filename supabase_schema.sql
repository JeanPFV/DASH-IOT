-- =====================================================================
-- IOT - controle de acesso por digital - schema para o Supabase
-- Cole tudo no Supabase > SQL Editor > New query e clique em Run.
-- Pode rodar mais de uma vez: só cria o que ainda não existe.
-- =====================================================================

-- Usuários do site. O "id" também é a posição da digital dentro do sensor
-- (o ESP32 grava a digital do usuário 5 na posição 5).
create table if not exists public.usuarios (
    id       integer generated by default as identity primary key,
    nome     varchar(50)  not null,
    email    varchar(50)  not null unique,
    senha    varchar(255) not null,               -- hash (pbkdf2 do Django), nunca texto puro
    digital  jsonb                                -- {"slot": 5, "cadastrada_em": "..."} ou null
);

-- Cada tentativa de entrar no site (por digital ou por senha) vira uma linha aqui.
-- É essa tabela que alimenta o dashboard.
create table if not exists public.acessos (
    id          bigint generated by default as identity primary key,
    usuario_id  integer references public.usuarios(id) on delete set null,
    metodo      varchar(10) not null check (metodo in ('digital', 'senha')),
    sucesso     boolean     not null,
    confianca   integer,                          -- nota de confiança do sensor (só digital)
    detalhe     varchar(120),
    criado_em   timestamptz not null default now()
);

create index if not exists acessos_criado_em_idx on public.acessos (criado_em desc);
create index if not exists acessos_usuario_idx   on public.acessos (usuario_id);

-- O Django conecta como "postgres" (dono das tabelas), então o RLS não atrapalha ele.
-- Ligar o RLS sem nenhuma policy fecha a API REST automática do Supabase
-- (quem tiver a anon key não consegue ler senhas nem acessos).
alter table public.usuarios enable row level security;
alter table public.acessos  enable row level security;

-- Limpeza da versão anterior (MetaBEE): se você já rodou o script antigo,
-- isto remove as tabelas de materiais e a coluna do Discord. Se não rodou, não faz nada.
drop table if exists public.historicomateriais;
drop table if exists public.materiais;
alter table public.usuarios drop column if exists userdiscord;
